from sklearn.linear_model import LinearRegression

# 2D list of Ad Spend feature inputs
X = [[10], [20], [30], [40], [50]]
# 1D list of Revenue targets
y = [150, 290, 440, 600, 720]

# scale of units, i.e., $ in 1000s
scale = 1000

# select and fit model
model = LinearRegression()
model.fit(X,y)

# Q1: Use linear regression to find the relationship between ad spend and revenue.
print("Q1: Use linear regression to find the relationship between ad spend and revenue:")
print("> w0 Intercept:", f"{model.intercept_:,.1f}")
print("> w1 Coefficient (i.e., slope):", f"{model.coef_[0]:,.1f}")
print("Therefore, Linear Regression Model is: y = " + str(f"{model.intercept_:,.1f}") +
      " + " + str(f"{model.coef_[0]:,.1f}") + "x")

# Q2: Predict revenue for an ad spend of $60k (i.e., 60)
print("\nQ2: Predict revenue for an ad spend of $60,000 (i.e., x=60)")
expected_revenue = model.predict([[60]])
formatted_revenue = f"${expected_revenue[0]*scale:,.0f}"
print("Expected revenue if ad spend is $60,000 is " + str(formatted_revenue) + ".")

# Q3: What does the slope of the line represent in this context?
print("\nQ3: What does the slope of the line represent in this context?")
print("The slope of this regression line represents the increase in revenue generated by each " +
    "additional unit of ad spend.")
print("In other words, for each additional unit (i.e.," + str(f"${1*scale:,.0f}") + ") of ad spend, " +
      "revenue increases by $" + str(f"{model.coef_[0]*scale:,.0f}") + ".")